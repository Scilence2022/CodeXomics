#!/usr/bin/env python3
"""Build the vendored catalog from the pinned Biopython Restriction_Dictionary.py."""

import argparse
import ast
import hashlib
import json
import re
from pathlib import Path

SOURCE_SHA256 = "2a79099295dbad6061ea67a11e053787c591fcb2eb10fc8c0f89ead908dfa02b"
OUTPUT = Path(__file__).resolve().parents[1] / "src/renderer/data/restriction-enzyme-catalog.js"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("dictionary", type=Path, help="Biopython 1.87 Restriction_Dictionary.py")
    data = parser.parse_args().dictionary.read_bytes()
    if hashlib.sha256(data).hexdigest() != SOURCE_SHA256:
        parser.error("Dictionary differs from the pinned Biopython 1.87 source")

    suppliers = {}
    enzymes = []
    for statement in ast.parse(data).body:
        if not isinstance(statement, ast.Assign) or not isinstance(statement.targets[0], ast.Subscript):
            continue
        target = statement.targets[0]
        name = ast.literal_eval(target.slice)
        if target.value.id == "suppliers":
            suppliers[name] = ast.literal_eval(statement.value)[0]
        elif target.value.id == "rest_dict":
            entry = ast.literal_eval(statement.value)
            top, bottom, extra_top, extra_bottom, motif = entry["charac"]
            if (
                entry["substrat"] == "DNA"
                and re.fullmatch("[ACGTRYSWKMBDHVN]+", motif)
                and top is not None
                and bottom is not None
                and extra_top is None
                and extra_bottom is None
            ):
                # Biopython records fst3 relative to the other end of the motif.
                enzymes.append([name, motif, top, len(motif) + bottom, "".join(entry["suppl"]), entry["id"]])

    header = """// Generated by scripts/generate-restriction-enzyme-catalog.py.
// Source: Biopython 1.87 Restriction_Dictionary.py (REBASE EMBOSS 404, 2024).
// https://github.com/biopython/biopython/blob/biopython-187/Bio/Restriction/Restriction_Dictionary.py
// Copyright (C) 2004 Frederic Sohm. See Biopython-LICENSE.txt.
// Columns: name, motif, top and bottom offsets from motif start, supplier codes, REBASE ID.
"""
    rows = "".join(f"    {json.dumps(row)},\n" for row in sorted(enzymes))
    OUTPUT.write_text(
        header
        + "// prettier-ignore\nconst restrictionEnzymeCatalog = {\n"
        + f"  suppliers: {json.dumps(suppliers, sort_keys=True)},\n"
        + "  enzymes: [\n"
        + rows
        + "  ],\n};\n"
        + "\nif (typeof module !== 'undefined' && module.exports) {\n"
        + "  module.exports = restrictionEnzymeCatalog;\n}\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
